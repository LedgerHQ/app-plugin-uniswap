class TestV4Swap:

    # Pure V4 exact-in on Base (UR 2.0): one V4_SWAP command, multi-hop path.
    def test_pure_v4_exact_in(self, backend, uniswap_contract_data, navigation_helper):
        client = UniswapClient(backend, uniswap_contract_data, chain_id=8453)
        client.set_external_plugin()
        client.provide_token_metadata_raw("TIN", "f8B3C47D4160052B4991B4753382000FB4675065", 18, 8453)
        client.provide_token_metadata_raw("TOU", "ac780b6E4Ee50585DF265c7766Cc2bED51E43fB8", 18, 8453)
        with client.send_raw_sign_request(PURE_V4_BASE):
            navigation_helper.ui_validate()

    # Mixed V2+V4 split on Base: the V4 leg swaps through an intermediate and
    # TAKEs it directly to the next V2 leg's pool pair (chaining plumbing).
    def test_mixed_v2_v4_take_to_pair(self, backend, uniswap_contract_data, navigation_helper):
        client = UniswapClient(backend, uniswap_contract_data, chain_id=8453)
        client.set_external_plugin()
        client.provide_token_metadata_raw("USDC", "833589fCD6eDb6E08f4c7C32D4f71b54bdA02913", 6, 8453)
        client.provide_token_metadata_raw("OUT2", "04D5ddf5f3a8939889F11E97f8c4BB48317F1938", 18, 8453)
        with client.send_raw_sign_request(MIXED_V2_V4_BASE):
            navigation_helper.ui_validate()

    # Pure V4 exact-in in the UR 2.1.1 layout (minHopPriceX36 arrays) on a
    # chain unknown to the ETH app (Robinhood, provisioned dynamically).
    def test_v4_ur_2_1_1_layout(self, backend, uniswap_contract_data, navigation_helper):
        client = UniswapClient(backend, uniswap_contract_data, chain_id=4663)
        client.client.provide_network_information(DynamicNetwork("Robinhood", "ETH", 4663))
        client.set_external_plugin()
        client.provide_token_metadata_raw("RIN", "5fc5360D0400a0Fd4f2af552ADD042D716F1d168", 2, 4663)
        client.provide_token_metadata_raw("ROU", "84b7515081A7Ac5adc26179b77A8B18A8c6725C0", 18, 4663)
        with client.send_raw_sign_request(V4_V211_ROBINHOOD):
            navigation_helper.ui_validate()

    # Native input on Arbitrum: an entry wrap, a wrapped V3 leg and a native
    # V4 leg (SETTLE of currency 0) merge into a single ETH -> token display.
    def test_v4_native_in_mixed(self, backend, uniswap_contract_data, navigation_helper):
        client = UniswapClient(backend, uniswap_contract_data, chain_id=42161)
        client.set_external_plugin()
        client.provide_token_metadata_raw("AOU", "94fCD9c18f99538C0f7C61c5500cA79F0D5C4dab", 18, 42161)
        # tx value = the quote's amountIn (the displayed native input)
        with client.send_raw_sign_request(NATIVE_IN_MIXED_ARBITRUM, amount=360032149501712):
            navigation_helper.ui_validate()
